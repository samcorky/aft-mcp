"""Generate ``.env.example`` and ``docs/settings.md`` from the settings groups.

Both files are written from each field's JSON Schema, description and example, so
they can't drift from the code. ``uv run poe settings-docs`` rewrites them, and
``uv run poe settings-docs-check`` (run by CI and a pre-commit hook) fails while
either is out of date. A secret never has a value written.
"""

import argparse
import re
import sys
import textwrap
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from aft_mcp.settings import GROUPS, AftMcpSettings

ENV_EXAMPLE_PATH = ".env.example"
SETTINGS_DOC_PATH = "docs/settings.md"
_GENERATED = "Generated by `uv run poe settings-docs`; do not edit."

_WIDTH = 88
_UNSAFE_IN_DOTENV = re.compile(r"[^\w./:@,+-]")
_FORMAT_TYPES = {"uri": "URL", "path": "path", "password": "secret"}
_JSON_TYPES = {
    "boolean": "true or false",
    "integer": "whole number",
    "number": "number",
    "string": "text",
}
_INTRO = (
    "Every setting is an environment variable. The server reads the process "
    + "environment first, then a `.env` file: the one named by `AFT_MCP_ENV_FILE` "
    + "(set in the environment), or else `aft-mcp/.env` in your config directory: "
    + "`$XDG_CONFIG_HOME` or `~/.config` on Linux and macOS, `%APPDATA%` on "
    + "Windows. The working directory is never read. Last come secret files: in "
    + "the directory named by `AFT_MCP_SECRETS_DIR` (or systemd's "
    + "`CREDENTIALS_DIRECTORY`), a file named after a variable, such as "
    + "`AFT_MCP_TOKEN`, holds its value. A variable "
    + "already in the environment wins, and an empty value counts as "
    + f"unset. [`{ENV_EXAMPLE_PATH}`](../{ENV_EXAMPLE_PATH}) is a starting point "
    + "to copy. A missing or invalid setting stops the server, and the error lists "
    + "every bad setting at once."
)

type JsonObject = dict[str, Any]


@dataclass(frozen=True, kw_only=True)
class SettingEntry:
    """One environment variable: how it is typed, defaulted and described."""

    env_name: str
    required: str
    """``yes`` or ``no``."""
    type_label: str
    allowed: str
    description: str
    default: str | None
    """The default as the variable carries it; ``None`` when there is none."""
    example: str | None
    starter: bool
    """Written uncommented in ``.env.example``, because a working setup needs it."""
    sensitive: bool


@dataclass(frozen=True, kw_only=True)
class SettingsSection:
    """One group of settings, as a heading and its variables."""

    title: str
    entries: list[SettingEntry]


def _resolve(node: Any, defs: JsonObject) -> Any:  # noqa: ANN401 - walks JSON Schema
    """Inline ``$ref``s to ``$defs``, as named types (``type CSV[T] = ...``) make."""
    if isinstance(node, dict):
        ref = node.get("$ref", "")
        if ref.startswith("#/$defs/"):
            target = defs[ref.removeprefix("#/$defs/")]
            node = {**target, **{k: v for k, v in node.items() if k != "$ref"}}
        return {key: _resolve(value, defs) for key, value in node.items()}
    if isinstance(node, list):
        return [_resolve(value, defs) for value in node]
    return node


def _without_null(schema: JsonObject) -> JsonObject:
    """The non-null member of an ``X | None`` schema, or the schema itself."""
    members = [m for m in schema.get("anyOf", []) if m.get("type") != "null"]
    return members[0] if len(members) == 1 else schema


def _bounds(schema: JsonObject) -> list[str]:
    allowed = []
    if (above := schema.get("exclusiveMinimum")) is not None:
        allowed.append(f"more than {above}")
    if schema.get("minLength") == 1 and schema.get("format") != "uri":
        allowed.append("not empty")
    return allowed


def _describe(schema: JsonObject) -> tuple[str, str]:
    """The type words and allowed-value phrases of one field's JSON Schema."""
    schema = _without_null(schema)
    if schema.get("type") == "array":
        items = schema.get("items", {})
        label, allowed = _describe(items)
        each = f"each {allowed}" if allowed else ""
        return f"comma-separated list of {label}s", each
    label = _FORMAT_TYPES.get(
        schema.get("format", ""), _JSON_TYPES.get(schema.get("type", ""), "text")
    )
    if label == "URL":
        return label, "`http://` or `https://`"
    if choices := schema.get("enum"):
        return label, " or ".join(f"`{choice}`" for choice in choices)
    return label, ", ".join(_bounds(schema))


def _text(value: object) -> str:
    """Render a JSON value the way an environment variable carries it."""
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def build_entries(group: type[AftMcpSettings]) -> list[SettingEntry]:
    """Describe every field of one group, in the order they are declared.

    Raises:
        ValueError: A field has no description, so it can't be documented.
    """
    schema = group.model_json_schema()
    schema = _resolve(schema, schema.get("$defs", {}))
    required = set(schema.get("required", []))
    prefix = group.model_config.get("env_prefix", "")
    entries = []
    for name, field in schema["properties"].items():
        if not field.get("description"):
            msg = f"{group.__name__}.{name} needs a description for {SETTINGS_DOC_PATH}"
            raise ValueError(msg)
        type_label, allowed = _describe(field)
        sensitive = _without_null(field).get("format") == "password"
        examples = field.get("examples", [])
        default = field.get("default")
        entries.append(
            SettingEntry(
                env_name=f"{prefix}{name.upper()}",
                required="yes" if name in required else "no",
                type_label=type_label,
                allowed=allowed,
                description=field["description"],
                default=None if default is None else _text(default),
                example=None if sensitive or not examples else _text(examples[0]),
                starter=name in required,
                sensitive=sensitive,
            )
        )
    return entries


def build_sections() -> list[SettingsSection]:
    """One section per settings group, in ``GROUPS`` order."""
    return [
        SettingsSection(title=group.title, entries=build_entries(group))
        for group in GROUPS.values()
    ]


def _dotenv_value(value: str) -> str:
    return f'"{value}"' if _UNSAFE_IN_DOTENV.search(value) else value


def _comment(text: str) -> list[str]:
    return [f"# {line}" for line in textwrap.wrap(text, _WIDTH - 2)]


def render_env_example(sections: list[SettingsSection]) -> str:
    """Render ``.env.example``: the needed settings set, the optional ones commented.

    A needed setting gets its example, or is left blank when it is a secret. An
    optional one is commented out with its example, or else its default.
    """
    lines = [
        f"# aft-mcp settings. {_GENERATED}",
        "# Copy to ~/.config/aft-mcp/.env (or a file named by AFT_MCP_ENV_FILE)",
        "# and fill in the settings that aren't commented out.",
        f"# Every variable is described in {SETTINGS_DOC_PATH}.",
    ]
    for section in sections:
        lines += ["", f"# --- {section.title} ---"]
        for entry in section.entries:
            lines += _env_example_entry(entry)
    return "\n".join(lines) + "\n"


def _env_example_entry(entry: SettingEntry) -> list[str]:
    lines = ["", *_comment(entry.description.replace("`", ""))]
    if entry.allowed:
        lines += _comment(f"Allowed: {entry.allowed.replace('`', '')}.")
    if entry.required != "no":
        lines += _comment(f"Required: {entry.required.replace('`', '')}.")
    if entry.sensitive:
        lines += _comment("Sensitive: no value is written here.")
    value = entry.example if entry.example is not None else entry.default
    prefix = "" if entry.starter else "# "
    lines.append(f"{prefix}{entry.env_name}={_dotenv_value(value or '')}")
    return lines


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _default_cell(entry: SettingEntry) -> str:
    if entry.default is not None:
        return f"`{entry.default}`"
    return "none" if entry.required == "yes" else "unset"


def _notes(entry: SettingEntry) -> str:
    notes = [entry.description]
    if entry.example is not None and entry.default is None:
        notes.append(f"Example: `{entry.example}`.")
    return " ".join(notes)


def render_settings_doc(sections: list[SettingsSection]) -> str:
    """Render the settings reference: one heading and table per group."""
    lines = [
        "# Settings reference",
        "",
        f"<!-- {_GENERATED} -->",
        "",
        _INTRO,
    ]
    for section in sections:
        lines += ["", f"## {section.title}", "", *_table(section.entries)]
    return "\n".join(lines) + "\n"


def _table(entries: list[SettingEntry]) -> list[str]:
    lines = [
        "| Variable | Required | Type | Default | Allowed values | Description |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    lines += [
        "| "
        + " | ".join(
            (
                f"`{entry.env_name}`",
                _cell(entry.required),
                _cell(entry.type_label),
                _cell(_default_cell(entry)),
                _cell(entry.allowed or "any"),
                _cell(_notes(entry)),
            )
        )
        + " |"
        for entry in entries
    ]
    return lines


def reference_files() -> dict[str, str]:
    """The generated files, as repository-relative paths and their contents."""
    sections = build_sections()
    return {
        ENV_EXAMPLE_PATH: render_env_example(sections),
        SETTINGS_DOC_PATH: render_settings_doc(sections),
    }


def write_reference_files(root: Path) -> list[str]:
    """Write each generated file under ``root`` that is out of date.

    Returns:
        The repository-relative paths that were rewritten.
    """
    files = reference_files()
    stale = stale_files(root)
    for name in stale:
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(files[name], encoding="utf-8", newline="\n")
    return stale


def stale_files(root: Path) -> list[str]:
    """The generated files under ``root`` that are missing or out of date."""
    return [
        name
        for name, text in reference_files().items()
        if not (root / name).is_file()
        or (root / name).read_text(encoding="utf-8") != text
    ]


def main(argv: list[str] | None = None) -> int:
    """Rewrite the generated files, or with ``--check`` only report stale ones."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--root", type=Path, default=Path(), help="repository root (default: .)"
    )
    parser.add_argument(
        "--check", action="store_true", help="write nothing; fail if a file is stale"
    )
    args = parser.parse_args(argv)
    if args.check:
        if stale := stale_files(args.root):
            print(
                f"Out of date: {', '.join(stale)}. Run `uv run poe settings-docs`.",
                file=sys.stderr,
            )
            return 1
        print("Settings reference is up to date")
        return 0
    written = write_reference_files(args.root)
    print(
        f"Updated {', '.join(written)}"
        if written
        else "Settings reference is up to date"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
